const ALIAS = { '’': "'", '‘': "'", '–': '-', '—': '-', '“': '"', '”': '"', 'œ': 'oe', 'Œ': 'OE', ' ': ' ', '\t': ' ' };

export const CW = 6;       // avance horizontale
export const LINE_H = 10;  // interligne
const CELL_H = 11;         // 2 lignes d'accents + 7 + 2 descendantes

let atlas = null;
const index = new Map();
const colorCache = new Map();

function makeCanvas(w, h) {
  if (typeof document !== 'undefined') { const c = document.createElement('canvas'); c.width = w; c.height = h; return c; }
  return new OffscreenCanvas(w, h);
}

function buildAtlas() {
  const chars = Object.keys(G).concat(Object.keys(COMPOSE));
  atlas = makeCanvas(chars.length * CW, CELL_H);
  const g = atlas.getContext('2d');
  g.fillStyle = '#fff';
  const plot = (ci, rows, oy) => {
    rows.forEach((r, y) => { for (let x = 0; x < r.length; x++) if (r[x] === '1') g.fillRect(ci * CW + x, y + oy, 1, 1); });
  };
  chars.forEach((ch, i) => {
    index.set(ch, i);
    if (G[ch] !== undefined) { plot(i, G[ch] ? G[ch].split('|') : [], 2); return; }
    const [base, acc] = COMPOSE[ch].split(' ');
    plot(i, G[base].split('|'), 2);
    const upper = base === base.toUpperCase() && base !== 'ı';
    if (acc === 'ced') plot(i, ACC.ced, 9);
    else plot(i, ACC[acc], upper ? 0 : 2);
  });
}

function atlasFor(color) {
  if (!atlas) buildAtlas();
  let c = colorCache.get(color);
  if (c) return c;
  c = makeCanvas(atlas.width, atlas.height);
  const g = c.getContext('2d');
  g.drawImage(atlas, 0, 0);
  g.globalCompositeOperation = 'source-in';
  g.fillStyle = color;
  g.fillRect(0, 0, c.width, c.height);
  if (colorCache.size > 96) colorCache.delete(colorCache.keys().next().value);
  colorCache.set(color, c);
  return c;
}

export function normText(s) {
  s = String(s);
  let out = '';
  for (const ch of s) out += ALIAS[ch] !== undefined ? ALIAS[ch] : ch;
  return out;
}

export function textWidth(str, scale = 1) {
  let n = 0;
  for (const _ of normText(str)) n++;
  return n * CW * scale;
}

// align: 'left' | 'center' | 'right'
export function drawText(g, str, x, y, color = '#fff', scale = 1, align = 'left') {
  str = normText(str);
  const a = atlasFor(color);
  if (align !== 'left') {
    const w = textWidth(str, scale) - scale;
    x -= align === 'center' ? Math.floor(w / 2) : w;
  }
  x = Math.round(x); y = Math.round(y);
  for (const ch of str) {
    let i = index.get(ch);
    if (i === undefined) i = index.get(ch.toUpperCase());
    if (i === undefined) i = index.get('?');
    if (ch !== ' ') g.drawImage(a, i * CW, 0, CW, CELL_H, x, y - 2 * scale, CW * scale, CELL_H * scale);
    x += CW * scale;
  }
  return x;
}

// Texte avec ombre portée (lisibilité sur fonds animés).
export function drawTextS(g, str, x, y, color = '#fff', scale = 1, align = 'left', shadow = '#000') {
  drawText(g, str, x + scale, y + scale, shadow, scale, align);
  return drawText(g, str, x, y, color, scale, align);
}

// Découpe en lignes de maxChars caractères (respecte les \n).
export function wrap(str, maxChars) {
  const out = [];
  for (const para of normText(str).split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const w of words) {
      if (!line.length) line = w;
      else if ((line + ' ' + w).length <= maxChars) line += ' ' + w;
      else { out.push(line); line = w; }
      while (line.length > maxChars) { out.push(line.slice(0, maxChars)); line = line.slice(maxChars); }
    }
    out.push(line);
  }
  return out;
}
